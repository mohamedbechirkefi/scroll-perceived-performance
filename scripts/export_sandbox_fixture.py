"""Parity fixture for the demo sandbox (demo/src/fixtures/sandbox_fixture.json).

The sandbox ports two pure parts of the research engine to TypeScript: the seeded latency and
failure schedule (src/scroll/schedule.py, twin of src/web/schedule.js) and the zero-overhead
reference model (src/scroll/reference.py). This script runs the Python originals on a few small
configurations; demo/src/engine.test.ts checks that the port gives the same values (delays and
outcomes exactly, times within 1e-9 ms). The browser harness, which produced every measured
result, is not ported: the sandbox computes schedule and lower bounds, it measures nothing.

Usage: PYTHONPATH=src .venv/bin/python scripts/export_sandbox_fixture.py [--check]
"""
from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from scroll import reference, schedule  # noqa: E402

OUT = ROOT / "demo" / "src" / "fixtures" / "sandbox_fixture.json"
JITTER = 0.1
K = 10
ARMS = {"read": ["BLANK", "SKELETON", "PREFETCH"], "write": ["BLANK", "OPTIMISTIC"]}
CASES = [
    {"seed": 1, "path": "read", "L": 50, "p": 0, "h": 150},
    {"seed": 7, "path": "read", "L": 300, "p": 0, "h": 150},
    {"seed": 20, "path": "read", "L": 1000, "p": 0, "h": 600},
    {"seed": 123456, "path": "read", "L": 237, "p": 0, "h": 0},
    {"seed": 3, "path": "write", "L": 100, "p": 0.1, "h": 0},
    {"seed": 11, "path": "write", "L": 1000, "p": 0.3, "h": 0},
    {"seed": 4294967295, "path": "write", "L": 640, "p": 0.5, "h": 0},
]


def simulate(seed: int, path: str, L: float, p: float, h: float) -> dict:
    trials = []
    for k in range(K):
        s = schedule.schedule(seed, path, k, L, JITTER, p if path == "write" else 0)
        arms = {}
        for arm in ARMS[path]:
            e = reference.expected(path, arm, s.delay_ms, ok=s.ok, lead_ms=h if arm == "PREFETCH" else 0.0)
            false_state = float(s.delay_ms) if (arm == "OPTIMISTIC" and not s.ok) else 0.0
            arms[arm] = {"ttuc_lb_ms": float(e.ttuc_lower_bound_ms), "ttff_lb_ms": float(e.ttff_lower_bound_ms), "false_state_lb_ms": false_state}
        trials.append({"k": k, "delay_ms": s.delay_ms, "ok": s.ok, "arms": arms})
    summary = {}
    for arm in ARMS[path]:
        ttuc = [t["arms"][arm]["ttuc_lb_ms"] for t in trials]
        diff = [t["arms"][arm]["ttuc_lb_ms"] - t["arms"]["BLANK"]["ttuc_lb_ms"] for t in trials]
        summary[arm] = {"median_ttuc_lb_ms": float(statistics.median(ttuc)), "median_diff_vs_blank_ms": float(statistics.median(diff))}
    return {"trials": trials, "summary": summary, "failures": sum(1 for t in trials if not t["ok"])}


def build() -> dict:
    return {
        "note": "Generated by scripts/export_sandbox_fixture.py from src/scroll/schedule.py and src/scroll/reference.py.",
        "jitter": JITTER,
        "k": K,
        "cases": [{"input": c, "output": simulate(c["seed"], c["path"], c["L"], c["p"], c["h"])} for c in CASES],
    }


def render(data: dict) -> str:
    return json.dumps(data, indent=1) + "\n"


def main(argv: list[str]) -> int:
    text = render(build())
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("FIXTURE-CHECK PASS" if ok else "FIXTURE-CHECK FAIL")
        return 0 if ok else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
